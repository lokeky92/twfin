def main() -> None:
    html_bytes = DOCS_HTML.read_bytes()
    gz_bytes = gzip.compress(html_bytes, compresslevel=9)
    b64_str = base64.b64encode(gz_bytes).decode("ascii")
    OUT_WORKER.write_text(WORKER_TEMPLATE.replace("__HTML_GZ_B64__", b64_str), encoding="utf-8")
    print(f"Wrote {OUT_WORKER} ({OUT_WORKER.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
